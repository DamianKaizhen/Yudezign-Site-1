// Helper function to get blog posts by category
export const getBlogPostsByCategory = (category: string): BlogPost[] => {
  return blogPosts.filter(post => post.category === category);
};

// Helper function to get blog posts by tag
export const getBlogPostsByTag = (tag: string): BlogPost[] => {
  return blogPosts.filter(post => post.tags.includes(tag));
};

// Helper function to get related blog posts
export const getRelatedBlogPosts = (currentSlug: string, limit: number = 3): BlogPost[] => {
  const currentPost = blogPosts.find(post => post.slug === currentSlug);
  if (!currentPost) return [];

  return blogPosts
    .filter(post => post.slug !== currentSlug && post.relatedPosts?.includes(currentSlug))
    .slice(0, limit);
};

// Helper function to get latest blog posts
export const getLatestBlogPosts = (limit: number = 6): BlogPost[] => {
  return [...blogPosts]
    .sort((a, b) => new Date(b.publishedDate).getTime() - new Date(a.publishedDate).getTime())
    .slice(0, limit);
};
